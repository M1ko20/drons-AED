// Source registry. Every researched number in the app points at one of these entries.
// `access` records how we actually read the source, so that weaker reads are visible.
// Titles stay in the original language; summaries are Czech.

export type SourceKind = 'peer-reviewed' | 'manufacturer' | 'official' | 'press' | 'dataset' | 'method'
export type StudyType = 'deployment' | 'experiment' | 'model' | 'claim' | 'authority' | 'dataset' | 'method' | 'press' | 'price'
export type Access = 'full' | 'page' | 'abstract' | 'memory'

export const STUDY_TYPE_LABEL: Record<StudyType, string> = {
  deployment: 'skutečný provoz',
  experiment: 'řízený experiment',
  model: 'simulace / optimalizace',
  claim: 'tvrzení výrobce',
  authority: 'předpis / stanovisko úřadu',
  dataset: 'datová sada',
  method: 'metodický odkaz',
  press: 'tisková zpráva / média',
  price: 'ceník prodejce',
}

export const ACCESS_LABEL: Record<Access, string> = {
  full: 'přečten plný text',
  page: 'přečtena oficiální stránka',
  abstract: 'jen abstrakt nebo shrnutí z vyhledávání',
  memory: 'neotevřeno (citováno ze znalosti oboru)',
}

